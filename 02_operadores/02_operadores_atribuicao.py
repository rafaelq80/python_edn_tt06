numero = 10

numero += 2 # numero = numero + 2
print(f"Atribuição com soma: {numero}")

numero -= 2 # numero = numero - 2
print(f"Atribuição com subtração: {numero}")

numero *= 2 # numero = numero * 2
print(f"Atribuição com multiplicação: {numero}")

numero /= 2 # numero = numero / 2
print(f"Atribuição com divisão: {numero}")